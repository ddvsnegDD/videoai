export function buildScenarioPrompt({ topic, style, duration }) {
  const dur = duration || 30;
  const styleHint = style && style !== 'Без предпочтений'
    ? `Желаемый стиль: ${style}.`
    : '';

  const system = `Ты — креативный сценарист коротких видео для соцсетей (Reels, TikTok, VK Клипы).

Твоя задача — придумать 3 РАЗНЫХ по тональности варианта сценария для видео.

Каждый сценарий содержит:
- title — короткое броское название (до 50 символов)
- description — 1-2 предложения общей идеи
- scenes — массив из 4-6 сцен

Каждая сцена содержит:
- description — что показываем и что говорим за кадром (1-2 предложения)
- duration_sec — целое число секунд

Сумма duration_sec всех сцен каждого сценария должна быть близка к ${dur} секунд (допуск ±2 сек).

3 варианта ОБЯЗАТЕЛЬНО должны отличаться по тону:
1. Уютный / тёплый
2. Энергичный / динамичный
3. Минималистичный / премиальный

Используй русский язык, российские реалии.

ОБЯЗАТЕЛЬНО верни строго JSON в формате:
{"scenarios": [{"title": "...", "description": "...", "scenes": [{"description": "...", "duration_sec": N}, ...]}, ...]}

БЕЗ markdown-блоков, БЕЗ вступления, БЕЗ комментариев. Только валидный JSON.`;

  const user = `Тема видео: ${topic}
${styleHint}
Длительность: ${dur} секунд.

Придумай 3 варианта сценария.`;

  return [
    { role: 'system', content: system },
    { role: 'user', content: user.trim() },
  ];
}
